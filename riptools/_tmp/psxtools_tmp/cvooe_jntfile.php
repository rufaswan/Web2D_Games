function cvooe( $fname )
{
	$file = load_bakfile($fname);
	if ( empty($file) )  return;

	$ed = strlen($file);
	$st = 0;
	while ( $st < $ed )
	{
		$opd = strpos($file, '.opd', $st);
		if ( $opd === false )
			break;

		$st = int_ceil($opd, -0x100);
		if ( substr($file,$st,2) !== "\x01\x23" )
			break;

		$cjnt = ord( $file[$st+0x26] );
		$chit = ord( $file[$st+0x29] );
		$cpss = ord( $file[$st+0x2a] );
		$cpnt = ord( $file[$st+0x2b] );
			$st += 0x30;

		// joints - skip
		$st += ($cjnt * 4);

		// poses
		for ( $ps=0; $ps < $cpss; $ps++ )
		{
			$st += 2;
			for ( $jn=0; $jn < $cjnt; $jn++ )
			{
				$file[$st+0] = "\x00";
				$file[$st+1] = "\x00";
					$st += 4;
			} // for ( $jn=0; $jn < $cjnt; $jn++ )
		} // for ( $ps=0; $ps < $cpss; $ps++ )

		// hitboxes - skip
		$st += ($chit * 8);

		// points
		for ( $pn=0; $pn < $cpnt; $pn++ )
		{
			$file[$st+0] = "\x00";
			$file[$st+1] = "\x00";
				$st += 4;
		} // for ( $pn=0; $pn < $cpnt; $pn++ )
	} // while ( $st < $ed )

	save_file($fname, $file);
	return;
}

for ( $i=1; $i < $argc; $i++ )
	cvooe( $argv[$i] );

