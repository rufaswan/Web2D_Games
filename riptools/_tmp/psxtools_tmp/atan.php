<?php
$x = [-1, 0,30,30, 0];
$y = [-1, 0, 0,30,30];

function t( $p1, $p2 )
{
	global $x, $y;
	$dx = $x[$p1] - $x[$p2];
	$dy = $y[$p1] - $y[$p2];
	$rot = atan( $dx/$dy ) * 0x80 / pi();

	echo "== atan $p1 - $p2\n";
	if ( $dy < 0 )
		$rot += 0x80;
	else
	if ( $dx < 0 )
		$rot += 0x100;
	printf("== rot %x\n", $rot);
	return;
}

// correct:
//   e0  0  20  20  0  e0
//      \|/        \|/
//   c0 -*- 40  40 -*- c0
//      /|\        /|\
//   a0 80  60  60 80  a0

t(1,2); // c0
t(1,3); // a0
t(1,4); // 80
t(2,1); // 40
t(2,3); // 80
t(2,4); // 60
t(3,1); // 20
t(3,2); //  0
t(3,4); // 40
t(4,1); //  0
t(4,2); // e0
t(4,3); // c0

